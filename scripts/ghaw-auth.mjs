/**
 * Validate the compiled Copilot Actions-token contract, not variable names.
 * https://docs.github.com/en/copilot/how-tos/copilot-cli/use-copilot-cli-in-actions
 */
export function authViolations(source, lock) {
  const credentials = lock.match(/COPILOT_GITHUB_TOKEN:\s*\$\{\{\s*github\.token\s*\}\}/g) ?? [];
  const exchanges = lock.match(/S2STOKENS:\s*["']?true\b/g) ?? [];
  const checks = {
    sourcePermission: /copilot-requests:\s*write\b/.test(source),
    compiledPermission: /copilot-requests:\s*write\b/.test(lock),
    ephemeralCredential: credentials.length > 0,
    exchangeEnabled: exchanges.length > 0 && exchanges.length === credentials.length,
    noStoredCopilotSecret: !/secrets\s*(?:\.\s*COPILOT_GITHUB_TOKEN|\[\s*["']COPILOT_GITHUB_TOKEN["']\s*\])/.test(source + lock),
    noBlanketWrite: !/\bwrite-all\b/.test(source + lock),
    pinnedRuntime: /uses:\s*github\/gh-aw-actions\/setup@53d0749e19424a918acd82b4d140264ce48f2f14\b/.test(lock),
    compatibleCompiler: /generated by gh-aw \(v1\.2\.2\)/.test(lock),
    fetchCompatibility: !/^\s+web-fetch:/m.test(source) || /copilot-sdk:\s*true\b/.test(source),
  };
  return Object.keys(checks).filter((name) => !checks[name]);
}
