import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { authViolations } from './ghaw-auth.mjs';

const source = 'permissions:\n  copilot-requests: write\n';
const lock = `# generated by gh-aw (v1.2.2)
copilot-requests: write
COPILOT_GITHUB_TOKEN: \${{ github.token }}
S2STOKENS: true
uses: github/gh-aw-actions/setup@53d0749e19424a918acd82b4d140264ce48f2f14
`;
test('ephemeral token environment is supported without stored secrets', () => {
  assert.deepEqual(authViolations(source, lock), []);
});
const regressions = [
  ['sourcePermission', '', lock],
  ['compiledPermission', source, lock.replace('copilot-requests: write', '')],
  ['ephemeralCredential', source, lock.replace('github.token', 'secrets.OTHER')],
  ['exchangeEnabled', source, lock.replace('S2STOKENS: true', '')],
  ['exchangeEnabled', source, lock + 'S2STOKENS: true\n'],
  ['noStoredCopilotSecret', source + 'token: ${{ secrets.COPILOT_GITHUB_TOKEN }}', lock],
  ['noStoredCopilotSecret', source, lock + `token: \${{ secrets['COPILOT_GITHUB_TOKEN'] }}`],
  ['noBlanketWrite', source + 'permissions: write-all', lock],
  ['pinnedRuntime', source, lock.replace('53d0749e19424a918acd82b4d140264ce48f2f14', 'main')],
  ['compatibleCompiler', source, lock.replace('v1.2.2', 'v0.45.2')],
  ['fetchCompatibility', source + 'tools:\n  web-fetch:\n', lock],
];
for (const [index, [violation, input, compiled]] of regressions.entries()) {
  test(`rejects ${violation} regression ${index}`, () => {
    assert.ok(authViolations(input, compiled).includes(violation));
  });
}
test('SDK mode preserves authored web fetch', () => {
  assert.deepEqual(authViolations(source + 'tools:\n  web-fetch:\nengine:\n  copilot-sdk: true\n', lock), []);
});
test('actual source and compiler output use tokenless inference', () => {
  const base = new URL('../.github/workflows/daily-testify-uber-super-expert', import.meta.url);
  assert.deepEqual(authViolations(readFileSync(new URL(`${base}.md`), 'utf8'), readFileSync(new URL(`${base}.lock.yml`), 'utf8')), []);
});
test('deployed schedule, strict mode, and tool-free smoke boundaries are preserved', () => {
  const compiled = readFileSync(new URL('../.github/workflows/daily-testify-uber-super-expert.lock.yml', import.meta.url), 'utf8');
  assert.match(compiled, /cron: "19 17 \* \* \*"/);
  assert.match(readFileSync(new URL('../.github/workflows/daily-testify-uber-super-expert.md', import.meta.url), 'utf8'), /strict: true/);
  const smoke = readFileSync(new URL('../.github/workflows/ghaw-auth-tests.yml', import.meta.url), 'utf8').split('  copilot-auth-smoke:')[1];
  assert.doesNotMatch(smoke, /uses:\s*actions\/checkout|secrets[.\[]/);
  assert.match(smoke, /head\.repo\.full_name == github\.repository/);
  assert.match(smoke, /--no-custom-instructions --disable-builtin-mcps/);
  assert.match(smoke, /--deny-tool read write shell url memory/);
});
